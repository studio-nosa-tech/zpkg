package cli

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/studio-nosa-tech/zpkg/internal/config"
)

// gitStamp records the commit that was installed from a git recipe source.
// It is kept inside the recipe tree so "zpkg sync" can compare the local
// state with the remote branch without shipping a .git directory.
const gitStampFile = ".zpkg-git"

type gitStamp struct {
	Remote string
	Branch string
	Commit string
}

func shortCommit(commit string) string {
	if len(commit) > 12 {
		return commit[:12]
	}
	return commit
}

func isGitSource(s string) bool {
	return strings.HasSuffix(s, ".git") ||
		strings.HasPrefix(s, "git@") ||
		strings.HasPrefix(s, "ssh://") ||
		strings.HasPrefix(s, "git://")
}

func readGitStamp(dir string) (gitStamp, error) {
	var st gitStamp
	data, err := os.ReadFile(filepath.Join(dir, gitStampFile))
	if err != nil {
		return st, err
	}
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, value, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		switch strings.TrimSpace(key) {
		case "remote":
			st.Remote = strings.TrimSpace(value)
		case "branch":
			st.Branch = strings.TrimSpace(value)
		case "commit":
			st.Commit = strings.TrimSpace(value)
		}
	}
	return st, nil
}

func writeGitStamp(dir string, st gitStamp) error {
	body := fmt.Sprintf("# generated by zpkg sync\nremote=%s\nbranch=%s\ncommit=%s\n",
		st.Remote, st.Branch, st.Commit)
	return os.WriteFile(filepath.Join(dir, gitStampFile), []byte(body), 0o644)
}

func gitCommand(git string, args ...string) ([]byte, error) {
	cmd := exec.Command(git, args...)
	cmd.Env = append(os.Environ(), "GIT_TERMINAL_PROMPT=0")
	out, err := cmd.CombinedOutput()
	if err != nil {
		msg := strings.TrimSpace(string(out))
		if msg == "" {
			return out, fmt.Errorf("git %s: %w", strings.Join(args, " "), err)
		}
		return out, fmt.Errorf("git %s: %w: %s", strings.Join(args, " "), err, msg)
	}
	return out, nil
}

func gitRemoteCommit(git, remote, branch string) (string, error) {
	out, err := gitCommand(git, "ls-remote", "--exit-code", remote, "refs/heads/"+branch)
	if err != nil {
		return "", fmt.Errorf("cannot read the recipe repository %s (branch %s): %w\n"+
			"private repositories need a git credential helper or an SSH key", remote, branch, err)
	}
	fields := strings.Fields(string(out))
	if len(fields) < 1 || len(fields[0]) < 40 {
		return "", fmt.Errorf("git ls-remote %s: unexpected output %q", remote, strings.TrimSpace(string(out)))
	}
	return fields[0], nil
}

// syncGitRecipes compares the commit in the local tree with the remote
// branch and clones only when they differ. The clone is staged and swapped
// atomically by installRecipeTree.
func syncGitRecipes(cfg config.Config, remote, branch, dest string, allowUnsigned, dryRun bool) (syncStats, error) {
	git, err := exec.LookPath("git")
	if err != nil {
		return syncStats{}, fmt.Errorf("git is required for a git recipe source; install it with \"zpkg install git\"")
	}
	if branch == "" {
		branch = "main"
	}
	remote = strings.TrimSpace(remote)
	if remote == "" {
		return syncStats{}, fmt.Errorf("no recipe repository URL")
	}

	remoteCommit, err := gitRemoteCommit(git, remote, branch)
	if err != nil {
		return syncStats{}, err
	}
	stamp, _ := readGitStamp(dest)
	localCommit := stamp.Commit
	if localCommit == "" {
		// A manually cloned tree may not carry .zpkg-git yet. Only trust a
		// repository rooted at dest itself; git would otherwise walk up to
		// an unrelated parent repository.
		if _, err := os.Stat(filepath.Join(dest, ".git")); err == nil {
			if out, err := gitCommand(git, "-C", dest, "rev-parse", "HEAD"); err == nil {
				localCommit = strings.TrimSpace(string(out))
			}
		}
	}
	if localCommit == remoteCommit && isRecipeTree(dest) {
		stats, err := scanRecipeTree(dest)
		if err != nil {
			return stats, err
		}
		stats.unchanged = true
		stats.commit = remoteCommit
		if stamp.Remote != remote || stamp.Branch != branch {
			// The URL/branch changed without changing the commit; refresh
			// the stamp so later syncs compare against the new remote.
			_ = writeGitStamp(dest, gitStamp{Remote: remote, Branch: branch, Commit: remoteCommit})
		}
		return stats, nil
	}

	parent := filepath.Dir(dest)
	tmp, err := os.MkdirTemp(parent, ".zignos-recipes-git-")
	if err != nil {
		return syncStats{}, err
	}
	defer os.RemoveAll(tmp)
	cloneDir := filepath.Join(tmp, "repo")
	phase("Fetching %s (branch %s)", remote, branch)
	if _, err := gitCommand(git, "clone", "--depth", "1", "--single-branch",
		"--branch", branch, remote, cloneDir); err != nil {
		return syncStats{}, err
	}
	srcRoot, err := findRecipeTree(cloneDir)
	if err != nil {
		return syncStats{}, err
	}
	stats, err := installRecipeTree(cfg, srcRoot, dest, allowUnsigned, dryRun,
		&gitStamp{Remote: remote, Branch: branch, Commit: remoteCommit})
	if err != nil {
		return stats, err
	}
	stats.commit = remoteCommit
	return stats, nil
}
